// Starts the server on a spare port with a temp data folder and checks the main flows.
'use strict';
const { spawn } = require('child_process');
const os = require('os'), path = require('path'), fs = require('fs');
const PORT = 18000 + Math.floor(Math.random() * 1000);
const DATA = fs.mkdtempSync(path.join(os.tmpdir(), 'oc-'));
const srv = spawn(process.execPath, [path.join(__dirname, 'server.js')], { env: Object.assign({}, process.env, { PORT, DATA_DIR: DATA }), stdio: 'inherit' });
const base = 'http://localhost:' + PORT;
const j = async (method, p, body) => { const r = await fetch(base + p, { method, headers: { 'Content-Type': 'application/json', Origin: 'http://localhost:3000' }, body: body ? JSON.stringify(body) : undefined }); return { status: r.status, body: await r.json(), cors: r.headers.get('access-control-allow-origin') }; };
const ok = (c, m) => { if (!c) { console.error('FAIL:', m); srv.kill(); process.exit(1); } console.log('ok -', m); };
(async () => {
  await new Promise(r => setTimeout(r, 400));
  const h = await j('GET', '/health'); ok(h.body.ok && h.body.day >= 1, 'health'); const day = h.body.day;
  const A = 'a'.repeat(16), B = 'b'.repeat(16), C = 'c'.repeat(16);
  const made = await j('POST', '/api/crews', { playerId: A, nick: 'Josh', name: 'Princess St Crew' });
  ok(made.status === 200 && /^[A-Z0-9]{6}$/.test(made.body.code), 'create crew'); ok(made.cors === 'http://localhost:3000', 'cors header');
  const code = made.body.code;
  ok((await j('POST', `/api/crews/${code}/join`, { playerId: B, nick: 'Maya' })).body.size === 2, 'join crew');
  await j('POST', `/api/crews/${code}/join`, { playerId: B, nick: 'Maya' });
  ok((await j('GET', `/api/crews/${code}`)).body.size === 2, 'joining twice does not duplicate');
  ok((await j('POST', '/api/score', { playerId: A, day, total: 3450, pts: [900, 650, 800, 600, 500] })).status === 200, 'post score');
  ok((await j('POST', '/api/score', { playerId: A, day, total: 5000, pts: [1000, 1000, 1000, 1000, 1000] })).body.total === 3450, 'first score of the day is kept');
  ok((await j('POST', '/api/score', { playerId: B, day, total: 9000, pts: [1000, 1000, 1000, 1000, 5000] })).status === 400, 'reject impossible score');
  ok((await j('POST', '/api/score', { playerId: B, day: day + 3, total: 100, pts: [20, 20, 20, 20, 20] })).status === 409, 'reject wrong day');
  await j('POST', '/api/score', { playerId: B, day, total: 3600, pts: [900, 900, 800, 500, 500] });
  const board = await j('GET', `/api/crews/${code}?playerId=${A}`);
  ok(board.body.played === 2 && board.body.members[0].nick === 'Maya' && board.body.members[1].you === true, 'board ranks scores and marks you');
  ok(!('id' in board.body.members[0]), 'player ids are not exposed');
  const me = await j('GET', `/api/me?playerId=${A}`); ok(me.body.crews.length === 1 && me.body.nick === 'Josh', 'my crews');
  ok((await j('POST', '/api/crews/ZZZZZZ/join', { playerId: C, nick: 'x' })).status === 404, 'unknown crew');
  ok((await j('POST', '/api/crews', { playerId: 'bad', name: 'x' })).status === 400, 'bad player id');
  const evil = await j('POST', '/api/crews', { playerId: C, nick: '<b>x</b>', name: '<script>' });
  ok(evil.status === 400 || !/[<>]/.test(evil.body.name || ''), 'strips < >');
  ok((await j('GET', '/api/stats')).body.playersToday === 2, 'stats');
  srv.kill('SIGTERM'); await new Promise(r => setTimeout(r, 300));
  ok(fs.existsSync(path.join(DATA, 'offcampus-data.json')), 'data saved to disk on shutdown');
  console.log('all tests passed'); process.exit(0);
})().catch(e => { console.error(e); srv.kill(); process.exit(1); });
